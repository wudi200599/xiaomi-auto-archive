export const cars: Car[] = baseCars.map((car) => {
  const interior = CAR_INTERIORS[car.slug];
  if (!interior) throw new Error(`车型 ${car.slug} 缺少内饰数据`);

  const sourceUrls = new Set(car.sources.map((source) => source.url));
  const extraSources = (CAR_SOURCE_ADDITIONS[car.slug] ?? []).filter((source) => {
    if (sourceUrls.has(source.url)) return false;
    sourceUrls.add(source.url);
    return true;
  });

  return {
    ...car,
    specs: { ...car.specs, ...(CAR_SPEC_FILLS[car.slug] ?? {}) },
    interior,
    sources: [...car.sources, ...extraSources],
  };
});

/** 按上市时间从新到旧排序（列表默认顺序） */
export function compareReleaseDesc(a: Car, b: Car): number {
  if (a.release !== b.release) return a.release < b.release ? 1 : -1;
  return a.name.localeCompare(b.name, 'zh');
}

export function getCarsBySeries(series: string): Car[] {
  return cars.filter((c) => c.series === series);
}

export function getCarsByGeneration(generationId: string): Car[] {
  return cars.filter((c) => c.generationId === generationId);
}
